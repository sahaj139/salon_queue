const ordinalEn = (n) => n + (n % 100 >= 11 && n % 100 <= 13 ? 'th' : ['th', 'st', 'nd', 'rd'][n % 10] || 'th');
export const ordinal = (lang, n) => (lang === 'gu' ? `${n}મા` : ordinalEn(n));

let lang = (() => { try { return localStorage.getItem('lang') || 'en'; } catch { return 'en'; } })();
const subs = new Set();
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('lang', l); } catch { /* private mode */ }
  document.documentElement.lang = l;
  subs.forEach((f) => f());
}

export function useLang() {
  const l = useSyncExternalStore((f) => (subs.add(f), () => subs.delete(f)), () => lang);
  const t = (key, vars = {}) => (dict[l][key] ?? dict.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  const name = (obj) => obj?.[l] || obj?.en || ''; // for {en, gu} names from data
  return { lang: l, t, name };
}
